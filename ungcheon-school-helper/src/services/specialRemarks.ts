// AI 출력에서 형식 위반(마크다운·불릿·따옴표·줄바꿈)을 결정론적으로 제거해
// 항상 "따옴표·불릿·줄바꿈 없는 하나의 완성된 문단"이 되도록 보장한다.
function sanitizeRemark(text: string): string {
  return text
    .replace(/\*\*|__|\*/g, '')                 // 마크다운 볼드/이탤릭
    .replace(/^\s*[-•▪‣◦]\s+/gm, '')            // 줄머리 불릿 (가운뎃점 ·은 한글 합성어와 충돌하므로 제외)
    .replace(/^\s*\d+[.)]\s+/gm, '')            // 줄머리 번호 매기기
    .replace(/[\r\n]+/g, ' ')                    // 줄바꿈 → 공백(한 문단화)
    .replace(/\s{2,}/g, ' ')                     // 다중 공백 축소
    .replace(/^["'“”‘’\s]+|["'“”‘’\s]+$/g, '')  // 앞뒤 따옴표/공백
    .trim()
}

