function randomIndex(length: number): number {
  if (typeof crypto !== 'undefined' && typeof crypto.getRandomValues === 'function') {
    const buffer = new Uint32Array(1)
    crypto.getRandomValues(buffer)
    return buffer[0] % length
  }
  return Math.floor(Math.random() * length)
}

export function drawLocalLuckyCard(kind: LuckyCardKind, previousId = ''): LocalLuckyCard {
  const deck = kind === 'tarot' ? TAROT : HWATU
  let index = randomIndex(deck.length)
  if (deck.length > 1 && `${kind}:${deck[index].id}` === previousId) index = (index + 1 + randomIndex(deck.length - 1)) % deck.length
  const seed = deck[index]
  return { ...seed, id: `${kind}:${seed.id}`, kind, message: seed.theme, luckyNumber: randomIndex(9) + 1 }
}
