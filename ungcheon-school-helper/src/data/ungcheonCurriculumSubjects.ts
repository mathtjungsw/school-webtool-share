function expandSeeds(
  seeds: SubjectSeed[],
  grade: 1 | 2 | 3,
  curriculum: CurriculumRevision,
): UngcheonCurriculumSubject[] {
  return seeds.map(([name, semesters, subjectGroup, subjectType, selectionGroup = '학교 지정']) => ({
    name,
    grade,
    semesters,
    curriculum,
    subjectGroup,
    subjectType,
    selectionGroup,
  }))
}

export const UNGCHEON_CURRICULUM_SUBJECTS: UngcheonCurriculumSubject[] = [
  ...expandSeeds(GRADE_1, 1, '2022 개정'),
  ...expandSeeds(GRADE_2, 2, '2022 개정'),
  ...expandSeeds(GRADE_3, 3, '2015 개정'),
]

export function getUngcheonSubjects(grade: 1 | 2 | 3, semester?: 1 | 2) {
  return UNGCHEON_CURRICULUM_SUBJECTS
    .filter((subject) => subject.grade === grade && (!semester || subject.semesters.includes(semester)))
    .sort((a, b) => {
      const groupOrder = a.selectionGroup.localeCompare(b.selectionGroup, 'ko')
      if (groupOrder !== 0) return groupOrder
      const subjectOrder = a.subjectGroup.localeCompare(b.subjectGroup, 'ko')
      return subjectOrder !== 0 ? subjectOrder : a.name.localeCompare(b.name, 'ko')
    })
}

export function normalizeOfficialSubjectName(value: string) {
  return value
    .normalize('NFKC')
    .replace(/[\s·ㆍ()\[\]{}_-]+/g, '')
    .replace(/[Ⅰ]/g, '1')
    .replace(/[Ⅱ]/g, '2')
    .toLowerCase()
}
