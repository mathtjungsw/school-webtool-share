export function extractSigungu(address: string): string {
  if (!address) return ''
  const parts = address.trim().split(/\s+/)
  const first = parts[0]

  if (first === '세종특별자치시') return first

  // 제주특별자치도 → 두 번째 토큰
  if (first === '제주특별자치도') return parts[1] ?? ''

  // 광역시·특별시 → 첫 토큰이 키
  if (first.endsWith('특별시') || first.endsWith('광역시')) {
    if (WEATHER_COORDS[first]) return first
  }

  // 도·특별자치도 → 시/군 토큰 탐색
  const sigungu = parts.find(p => p.endsWith('시') || p.endsWith('군')) ?? ''
  if (!sigungu) return first

  // 고성군처럼 동명이 있는 경우 도 접두어 복합 키 우선 시도
  const provincePrefix =
    address.includes('강원') ? '강원' :
    address.includes('경상남도') || address.includes('경남') ? '경남' : ''

  if (provincePrefix) {
    const composite = `${provincePrefix}_${sigungu}`
    if (WEATHER_COORDS[composite]) return composite
  }

  return sigungu
}
